"""Generate shared browser metadata from the Python model (or check for drift)."""
import json
import sys
from dataclasses import asdict
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from retaining_wall.core import Wall, VERSION, SOURCE, presets, analyze
from retaining_wall.regulations import PROFILES, MOVEMENTS, LOAD_CASES
r = analyze({})
data = dict(version=VERSION, source=SOURCE, defaults=asdict(Wall()), presets=presets(),
            profiles=PROFILES, movements=MOVEMENTS, load_cases=LOAD_CASES,
            assumptions=r['assumptions'], rc=r['rc'], references=r['references'],
            outstanding=r['outstanding'], review_date=r['regulation']['review_date'])
text = '// Generated by scripts/sync_browser_model.py; do not edit by hand.\nexport const MODEL = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
p = ROOT / 'browser/model-data.mjs'
if '--check' in sys.argv:
    if p.read_text() != text:
        raise SystemExit('Browser metadata is stale; run scripts/sync_browser_model.py')
else:
    p.write_text(text)

# Package the same reviewed UI with the Python app; keep the original UI files.
import shutil
out = ROOT / 'retaining_wall/web/professional'
if '--check' not in sys.argv:
    out.mkdir(exist_ok=True)
for name in ('index.html', 'app.mjs', 'engine.mjs', 'model-data.mjs', 'style.css'):
    source = ROOT / 'browser' / name
    target = out / name
    if '--check' in sys.argv:
        if not target.exists() or target.read_bytes() != source.read_bytes():
            raise SystemExit('Packaged browser assets are stale: ' + name)
    else:
        shutil.copyfile(source, target)
